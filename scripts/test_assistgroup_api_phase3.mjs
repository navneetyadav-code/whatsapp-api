import mysql from '../worker/node_modules/mysql2/promise.js';
import crypto from 'crypto';

const BASE_URL = 'http://localhost/assistgroup/api/admin/v1';

async function main() {
  console.log('====================================================');
  console.log(' TESTING ASSISTGROUP ADMIN API PHASE 3 (OPERATIONS) ');
  console.log('====================================================');

  const db = await mysql.createConnection({
    host: '127.0.0.1',
    user: 'root',
    password: '',
    database: 'assistgroup'
  });

  const [admins] = await db.query('SELECT id, Admin_Name, email FROM admin_login LIMIT 1');
  const admin = admins[0];

  const rawSecret = crypto.randomBytes(32).toString('hex');
  const token = `ast_live_${rawSecret}`;
  const tokenPrefix = token.substring(0, 16);
  const tokenHash = crypto.createHash('sha256').update(token).digest('hex');
  const expiresAt = new Date(Date.now() + 24 * 3600 * 1000).toISOString().slice(0, 19).replace('T', ' ');

  await db.execute(
    `INSERT INTO admin_api_tokens (admin_id, name, token_prefix, token_hash, scopes, expires_at)
     VALUES (?, ?, ?, ?, ?, ?)`,
    [admin.id, 'Phase 3 Test Runner', tokenPrefix, tokenHash, JSON.stringify(['*']), expiresAt]
  );

  const authHeaders = {
    'Authorization': `Bearer ${token}`,
    'Content-Type': 'application/json'
  };

  let passed = 0;
  let failed = 0;

  async function test(name, fn) {
    try {
      process.stdout.write(`[Test] ${name} ... `);
      await fn();
      console.log('✅ PASS');
      passed++;
    } catch (err) {
      console.log(`❌ FAIL\n  Error: ${err.message}`);
      failed++;
    }
  }

  // --------------------------------------------------------------------------
  // INQUIRIES TESTS
  // --------------------------------------------------------------------------
  await test('GET /inquiries (list with pagination)', async () => {
    const res = await fetch(`${BASE_URL}/inquiries?limit=5`, { headers: authHeaders });
    const json = await res.json();
    if (res.status !== 200 || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
    if (!Array.isArray(json.data) || !json.meta?.pagination) throw new Error('Invalid inquiries structure');
  });

  // Create temporary inquiry row in DB
  const [inqInsert] = await db.execute(
    `INSERT INTO contact_inquiries (ticket_token, full_name, email, phone, service_type, subject, message, status, created_at)
     VALUES (?, ?, ?, ?, ?, ?, ?, "new", NOW())`,
    [
      'TKT-' + crypto.randomBytes(4).toString('hex').toUpperCase(),
      'API Test Customer',
      'customer@apitest.local',
      '+919123456789',
      'Technical Support',
      'API Automation Inquiry Test',
      'This is an automated inquiry test message generated by Phase 3 runner.'
    ]
  );
  const testInquiryId = inqInsert.insertId;

  await test(`GET /inquiries/${testInquiryId}`, async () => {
    const res = await fetch(`${BASE_URL}/inquiries/${testInquiryId}`, { headers: authHeaders });
    const json = await res.json();
    if (res.status !== 200 || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
    if (json.data.full_name !== 'API Test Customer') throw new Error('Inquiry details mismatch');
  });

  await test(`PATCH /inquiries/${testInquiryId}/status (mark in_progress)`, async () => {
    const res = await fetch(`${BASE_URL}/inquiries/${testInquiryId}/status`, {
      method: 'PATCH',
      headers: authHeaders,
      body: JSON.stringify({ status: 'in_progress' })
    });
    const json = await res.json();
    if (res.status !== 200 || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
    if (json.data.status !== 'in_progress') throw new Error('Status not updated');
  });

  await test(`PATCH /inquiries/${testInquiryId}/notes (save internal notes)`, async () => {
    const res = await fetch(`${BASE_URL}/inquiries/${testInquiryId}/notes`, {
      method: 'PATCH',
      headers: authHeaders,
      body: JSON.stringify({ notes: 'Customer contacted via API runner. Follow-up priority.' })
    });
    const json = await res.json();
    if (res.status !== 200 || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
    if (!json.data.admin_notes.includes('Follow-up priority')) throw new Error('Notes not saved');
  });

  await test(`POST /inquiries/${testInquiryId}/reply (dispatch response)`, async () => {
    const res = await fetch(`${BASE_URL}/inquiries/${testInquiryId}/reply`, {
      method: 'POST',
      headers: authHeaders,
      body: JSON.stringify({
        channel: 'email',
        reply: 'Thank you for reaching out. Your request has been acknowledged by our engineering team.',
        new_status: 'resolved'
      })
    });
    const json = await res.json();
    if (res.status !== 200 || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
    if (json.data.status !== 'resolved') throw new Error('Status not resolved after reply');
  });

  await test(`DELETE /inquiries/${testInquiryId}`, async () => {
    const res = await fetch(`${BASE_URL}/inquiries/${testInquiryId}`, {
      method: 'DELETE',
      headers: authHeaders
    });
    const json = await res.json();
    if (res.status !== 200 || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
  });

  // --------------------------------------------------------------------------
  // FILES & STORAGE TESTS
  // --------------------------------------------------------------------------
  await test('GET /files (file catalog index)', async () => {
    const res = await fetch(`${BASE_URL}/files?limit=5`, { headers: authHeaders });
    const json = await res.json();
    if (res.status !== 200 || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
    if (!Array.isArray(json.data) || !json.meta?.pagination) throw new Error('Invalid files structure');
  });

  await test('GET /files/orphans (scan orphaned disk files)', async () => {
    const res = await fetch(`${BASE_URL}/files/orphans`, { headers: authHeaders });
    const json = await res.json();
    if (res.status !== 200 || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
    if (typeof json.data.orphan_count !== 'number') throw new Error('Invalid orphan scan response');
  });

  await test('POST /files/purge-expired (cleanup expired assets)', async () => {
    const res = await fetch(`${BASE_URL}/files/purge-expired`, {
      method: 'POST',
      headers: authHeaders
    });
    const json = await res.json();
    if (res.status !== 200 || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
    if (typeof json.data.purged_count !== 'number') throw new Error('Invalid purge response');
  });

  // --------------------------------------------------------------------------
  // PRICING & GOD-MODE TESTS
  // --------------------------------------------------------------------------
  await test('GET /pricing/plans (list all plans & entitlements)', async () => {
    const res = await fetch(`${BASE_URL}/pricing/plans`, { headers: authHeaders });
    const json = await res.json();
    if (res.status !== 200 || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
    if (!Array.isArray(json.data)) throw new Error('Invalid plans array');
  });

  let createdPlanId = null;
  const testPlanSlug = `test-plan-${Date.now()}`;

  await test('POST /pricing/plans (create new plan)', async () => {
    const res = await fetch(`${BASE_URL}/pricing/plans`, {
      method: 'POST',
      headers: authHeaders,
      body: JSON.stringify({
        name: 'API VIP Plan',
        slug: testPlanSlug,
        description: 'Automated test subscription plan',
        price_monthly_inr: 499,
        price_yearly_inr: 4990,
        trial_days: 14,
        badge_text: 'Beta',
        sort_order: 99
      })
    });
    const json = await res.json();
    if ((res.status !== 200 && res.status !== 201) || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
    createdPlanId = json.data.id;
    if (!createdPlanId) throw new Error('Missing created plan ID');
  });

  await test(`GET /pricing/plans/${createdPlanId}`, async () => {
    const res = await fetch(`${BASE_URL}/pricing/plans/${createdPlanId}`, { headers: authHeaders });
    const json = await res.json();
    if (res.status !== 200 || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
    if (json.data.slug !== testPlanSlug) throw new Error('Plan slug mismatch');
  });

  await test(`PATCH /pricing/plans/${createdPlanId}/archive`, async () => {
    const res = await fetch(`${BASE_URL}/pricing/plans/${createdPlanId}/archive`, {
      method: 'PATCH',
      headers: authHeaders
    });
    const json = await res.json();
    if (res.status !== 200 || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
    if (json.data.status !== 'archived') throw new Error('Plan status not archived');
  });

  await test(`PATCH /pricing/plans/${createdPlanId}/activate`, async () => {
    const res = await fetch(`${BASE_URL}/pricing/plans/${createdPlanId}/activate`, {
      method: 'PATCH',
      headers: authHeaders
    });
    const json = await res.json();
    if (res.status !== 200 || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
    if (json.data.status !== 'active') throw new Error('Plan status not active');
  });

  // Clean up created test plan
  await db.execute('DELETE FROM subscription_plans WHERE id = ?', [createdPlanId]);

  // God-Mode Tests
  await test('GET /pricing/god-mode (list VIP grants)', async () => {
    const res = await fetch(`${BASE_URL}/pricing/god-mode`, { headers: authHeaders });
    const json = await res.json();
    if (res.status !== 200 || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
    if (!Array.isArray(json.data)) throw new Error('Invalid god-mode grants response');
  });

  // Find a test user for god-mode grant
  const [testUsers] = await db.query('SELECT id, username FROM loginuser LIMIT 1');
  if (testUsers.length > 0) {
    const targetUser = testUsers[0];
    let grantId = null;

    await test(`POST /pricing/god-mode (grant to user ${targetUser.id})`, async () => {
      const res = await fetch(`${BASE_URL}/pricing/god-mode`, {
        method: 'POST',
        headers: authHeaders,
        body: JSON.stringify({
          user_id: targetUser.id,
          reason: 'API Automated VIP Testing',
          duration_days: 7
        })
      });
      const json = await res.json();
      if (res.status !== 201 || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
      grantId = json.data.grant_id;
      if (!grantId) throw new Error('Missing grant ID');
    });

    if (grantId) {
      await test(`DELETE /pricing/god-mode/${grantId} (revoke grant)`, async () => {
        const res = await fetch(`${BASE_URL}/pricing/god-mode/${grantId}`, {
          method: 'DELETE',
          headers: authHeaders,
          body: JSON.stringify({ reason: 'API automated test cleanup' })
        });
        const json = await res.json();
        if (res.status !== 200 || !json.success) throw new Error(json.error || `HTTP ${res.status}`);
      });
    }
  }

  // Cleanup test runner token
  await db.execute('DELETE FROM admin_api_tokens WHERE name = "Phase 3 Test Runner"');
  await db.end();

  console.log('\n====================================================');
  console.log(` RESULTS: ${passed} Passed, ${failed} Failed`);
  console.log('====================================================');
}

main().catch(err => {
  console.error('Fatal test error:', err);
  process.exit(1);
});
